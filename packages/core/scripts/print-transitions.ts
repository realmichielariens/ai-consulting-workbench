// Prints the I1 lifecycle table (rules/lifecycle.ts) as Markdown, run by
// `pnpm core:transitions` (I1-PLAN.md §6 W3, look L3). Every row below is
// produced by actually calling applyItemEvent with the listed scenario, so
// this also doubles as a consistency check: an unexpectedly denied scenario
// fails the script (exit 1) instead of silently printing a stale table.

import { applyItemEvent, type ItemEvent, type ItemEventContext } from "../src/rules/lifecycle.js";
import type { ItemStatus } from "../src/domain.js";

interface Scenario {
  from: ItemStatus;
  event: ItemEvent;
  ctx: ItemEventContext;
  condition: string;
}

const eventLabel = (e: ItemEvent): string => (e.type === "run_ended" ? `run_ended (${e.outcome})` : e.type);

const scenarios: Scenario[] = [
  { from: "waiting", event: { type: "inputs_ready" }, ctx: { executor: "agent" }, condition: "every required input published, sequencing done" },
  { from: "ready", event: { type: "inputs_missing" }, ctx: { executor: "agent" }, condition: "a required input is no longer published" },
  { from: "ready", event: { type: "start" }, ctx: { executor: "agent" }, condition: "agent items (autostart or the human clicks Start)" },
  { from: "ready", event: { type: "human_upload" }, ctx: { executor: "human" }, condition: "human items, first upload (J1.6)" },
  { from: "in_progress", event: { type: "human_upload" }, ctx: { executor: "human" }, condition: "human items, further uploads before Mark done" },
  {
    from: "in_progress",
    event: { type: "run_ended", outcome: "submitted" },
    ctx: { executor: "agent", hasGateChain: true },
    condition: "gate chain non-empty",
  },
  {
    from: "in_progress",
    event: { type: "run_ended", outcome: "submitted" },
    ctx: { executor: "agent", hasGateChain: false },
    condition: "no gate",
  },
  {
    from: "in_progress",
    event: { type: "run_ended", outcome: "blocked" },
    ctx: { executor: "agent" },
    condition: "opens a blocking question (J1.4)",
  },
  {
    from: "in_progress",
    event: { type: "run_ended", outcome: "no_submit" },
    ctx: { executor: "agent" },
    condition: "no submit, no question, after the one nudge -> run issue (R3)",
  },
  {
    from: "in_progress",
    event: { type: "run_ended", outcome: "max_turns" },
    ctx: { executor: "agent" },
    condition: "hit maxTurns -> run issue (R3)",
  },
  {
    from: "in_progress",
    event: { type: "run_ended", outcome: "error" },
    ctx: { executor: "agent" },
    condition: "SDK/process error -> run issue (R3)",
  },
  {
    from: "in_progress",
    event: { type: "run_ended", outcome: "interrupted" },
    ctx: { executor: "agent" },
    condition: "server restart or crash -> resumable, session kept (R1)",
  },
  { from: "in_progress", event: { type: "stop" }, ctx: { executor: "agent" }, condition: "human clicks Stop -> resumable, session kept (R5)" },
  {
    from: "in_progress",
    event: { type: "mark_done" },
    ctx: { executor: "human", allRequiredOutputsPublished: true },
    condition: "human items, every required output published (J1.6)",
  },
  { from: "blocked", event: { type: "question_answered" }, ctx: { executor: "agent" }, condition: "resume-answer (J1.4)" },
  { from: "blocked", event: { type: "issue_retry" }, ctx: { executor: "agent" }, condition: "human clicks Retry on a run issue (R3)" },
  { from: "blocked", event: { type: "issue_stop" }, ctx: { executor: "agent" }, condition: "human clicks Stop on a run issue (R3)" },
  { from: "at_gate", event: { type: "gate_approved" }, ctx: { executor: "agent", isLastGateStep: true }, condition: "last step in the chain (I1: always)" },
  {
    from: "at_gate",
    event: { type: "gate_approved" },
    ctx: { executor: "agent", isLastGateStep: false },
    condition: "not the last step, stays at_gate (chains arrive in I6)",
  },
  { from: "at_gate", event: { type: "changes_requested" }, ctx: { executor: "agent" }, condition: "changes-requested (J1.5), run resumes" },
];

const rows = scenarios.map((s) => {
  const result = applyItemEvent(s.from, s.event, s.ctx);
  if (!result.ok) {
    throw new Error(`scenario unexpectedly denied: ${s.from} + ${eventLabel(s.event)} -> ${result.reason}`);
  }
  return { from: s.from, event: eventLabel(s.event), to: result.to, condition: s.condition };
});

const lines: string[] = [];
lines.push("# I1 lifecycle transitions");
lines.push("");
lines.push("Generated by `pnpm core:transitions` from `packages/core/src/rules/lifecycle.ts`.");
lines.push("Compare against DESIGN.md §4.2 and the R5 clarification (I1-PLAN.md §6 W3, look L3).");
lines.push("");
lines.push("| From | Event | To | Condition |");
lines.push("|---|---|---|---|");
for (const r of rows) {
  lines.push(`| ${r.from} | ${r.event} | ${r.to} | ${r.condition} |`);
}
lines.push("");
lines.push(`${rows.length} transitions checked, all as expected.`);

console.log(lines.join("\n"));
