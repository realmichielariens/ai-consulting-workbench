// createFakeRuntime(): the scripted fake agent (ports.ts AgentRuntime, kind
// "fake"). Drives the SAME WorkPort as the real runtime and emits the same
// kinds of ActivityItems, from YAML scripts in packages/agents/fake-scripts/
// (scripts.ts), so the server, UI and Playwright journeys never need to know
// which runtime they're talking to. A configurable delay between steps lets a
// human watch it work; WORKBENCH_FAKE_DELAY_MS=0 makes it instant for tests.

import fs from "node:fs";
import path from "node:path";
import type {
  ActivityItem,
  AgentRuntime,
  BriefView,
  RunHandle,
  RunOutcome,
  RunResult,
  StartRunRequest,
} from "@workbench/core";
import { FakeItemScript, loadFakeScript, type FakeStep } from "./scripts.js";

export interface FakeRuntimeOptions {
  /** Absolute path to packages/agents/fake-scripts. Defaults to the sibling of this package's src/. */
  scriptsDir?: string;
  /** ms between steps. Defaults to WORKBENCH_FAKE_DELAY_MS, else 600; pass 0 in tests. */
  delayMs?: number;
  /** Defaults to WORKBENCH_FAKE_VARIANT. "no-submit" forces R3; "denial" prepends a demo guard denial (R4). */
  variant?: string;
}

function sleep(ms: number): Promise<void> {
  return ms <= 0 ? Promise.resolve() : new Promise((resolve) => setTimeout(resolve, ms));
}

function truncate(text: string, max: number): string {
  const t = text.trim();
  return t.length <= max ? t : `${t.slice(0, max - 1)}…`;
}

function resolveDelay(opts: FakeRuntimeOptions): number {
  if (opts.delayMs !== undefined) return opts.delayMs;
  const env = process.env.WORKBENCH_FAKE_DELAY_MS;
  if (env !== undefined) {
    const n = Number(env);
    if (!Number.isNaN(n)) return n;
  }
  return 600;
}

export function defaultFakeScriptsDir(): string {
  return path.resolve(import.meta.dirname, "../../fake-scripts");
}

/** Any agent item without a dedicated fake-scripts/<id>.yaml: publish a short placeholder per required output, then submit. */
function fallbackScript(brief: BriefView): FakeStep[] {
  const steps: FakeStep[] = [
    { text: `Working ${brief.itemId} — ${brief.title} (generic fallback fake script; no dedicated script for this item).` },
  ];
  const required = brief.outputs.filter((o) => o.required);
  for (const output of required) {
    const fileName = `${output.slot}.md`;
    steps.push({
      write: {
        path: fileName,
        content: `# ${output.slot}\n\nPlaceholder output for ${brief.itemId} (${brief.title}), generated by the generic fallback fake script.\n`,
      },
    });
    steps.push({ publish: { slot: output.slot, sourcePath: fileName, kind: "material", note: "Placeholder output from the generic fallback fake script." } });
  }
  steps.push({ worklog: `Generic fallback: published a placeholder for each of ${required.length} required output slot(s).` });
  steps.push({
    submit: {
      summary: `Published a placeholder for every required output of ${brief.itemId}.`,
      selfCheck: brief.acceptance.map((criterion) => ({ criterion, met: "partial" as const, note: "Placeholder output from the generic fallback fake script; not a real evaluation." })),
      openIssues: ["This item has no dedicated fake script; outputs are generic placeholders."],
    },
  });
  return steps;
}

/** For reason "resume": if every required output is already published, just resubmit; otherwise replay "start" (or the fallback). */
function resumeScript(itemScript: FakeItemScript | null, brief: BriefView): FakeStep[] {
  const allPublished = brief.outputs.filter((o) => o.required).every((o) => o.latestVersion != null);
  if (allPublished) {
    return [
      { text: "Resuming: every required output is already published. Re-checking and submitting." },
      {
        submit: {
          summary: "Outputs were already complete; resubmitting after the interruption.",
          selfCheck: brief.acceptance.map((criterion) => ({ criterion, met: "yes" as const, note: "Already satisfied before the interruption." })),
          openIssues: [],
        },
      },
    ];
  }
  return itemScript?.start ?? fallbackScript(brief);
}

function selectSteps(scriptsDir: string, req: StartRunRequest, brief: BriefView): FakeStep[] {
  const itemScript = loadFakeScript(scriptsDir, req.item.id);
  if (req.reason === "resume") return resumeScript(itemScript, brief);
  const steps = itemScript?.[req.reason];
  return steps ?? fallbackScript(brief);
}

export function createFakeRuntime(opts: FakeRuntimeOptions = {}): AgentRuntime {
  const scriptsDir = opts.scriptsDir ?? defaultFakeScriptsDir();
  const delayMs = resolveDelay(opts);
  const variant = opts.variant ?? process.env.WORKBENCH_FAKE_VARIANT;

  return {
    kind: "fake",
    startRun(req: StartRunRequest): RunHandle {
      const state = { interrupted: false };
      const done = runFakeScript(req, scriptsDir, delayMs, variant, state);
      return {
        runId: req.runId,
        interrupt: async () => {
          state.interrupted = true;
        },
        done,
      };
    },
  };
}

async function runFakeScript(
  req: StartRunRequest,
  scriptsDir: string,
  delayMs: number,
  variant: string | undefined,
  state: { interrupted: boolean },
): Promise<RunResult> {
  const { item, paths, workPort, observer } = req;
  let idx = 0;
  const push = (partial: Omit<ActivityItem, "idx" | "at">): ActivityItem => {
    const activityItem: ActivityItem = { idx: idx++, at: new Date().toISOString(), ...partial };
    observer.onActivity(activityItem);
    return activityItem;
  };

  push({ kind: "system", summary: `Started (${req.reason}, fake)` });
  observer.onSession(`fake-${req.runId}`);

  let submitted = false;
  let openBlockingQuestion = false;
  let forcedOutcome: RunOutcome | null = null;
  let denials = 0;
  let lastText = "";
  let stepCount = 0;

  try {
    const brief = await workPort.getBrief();
    const scripted = selectSteps(scriptsDir, req, brief);
    const steps: FakeStep[] =
      variant === "denial" ? [{ deny: { tool: "Read", reason: "Read of another item's work/ is not allowed (fake demo)." } }, ...scripted] : scripted;

    for (const step of steps) {
      if (state.interrupted) {
        forcedOutcome = "interrupted";
        break;
      }
      await sleep(delayMs);
      stepCount++;

      if ("text" in step) {
        lastText = step.text;
        push({ kind: "text", summary: truncate(step.text, 160), detail: step.text });
      } else if ("read" in step) {
        const input = brief.inputs.find((i) => i.slot === step.read);
        const label = input?.version ? `${step.read} v${input.version}` : step.read;
        push({ kind: "tool", summary: `Read ${label}`, tool: { name: "Read", input: { slot: step.read } } });
      } else if ("write" in step) {
        const abs = path.join(paths.itemWork(item.id), step.write.path);
        fs.mkdirSync(path.dirname(abs), { recursive: true });
        fs.writeFileSync(abs, step.write.content, "utf8");
        push({ kind: "tool", summary: `Wrote work/${step.write.path}`, tool: { name: "Write", input: { file_path: abs } } });
      } else if ("publish" in step) {
        const result = await workPort.publishAsset(step.publish);
        push({
          kind: "publish",
          summary: `Published ${result.slot} v${result.version} (${step.publish.kind})`,
          tool: { name: "mcp__work__publish_asset", input: step.publish },
        });
      } else if ("worklog" in step) {
        await workPort.appendWorklog({ entry: step.worklog });
        push({ kind: "tool", summary: "Appended a worklog entry", detail: step.worklog, tool: { name: "mcp__work__append_worklog", input: { entry: step.worklog } } });
      } else if ("question" in step) {
        const result = await workPort.raiseQuestion(step.question);
        if (step.question.blocking) openBlockingQuestion = true;
        push({
          kind: "question",
          summary: `Asked ${step.question.blocking ? "a blocking question" : "a question"}: ${truncate(step.question.question, 140)}`,
          detail: result.instruction,
          tool: { name: "mcp__work__raise_question", input: step.question },
        });
        if (step.question.blocking) break; // same protocol as the real agent: end the turn right after a blocking question
      } else if ("progress" in step) {
        await workPort.reportProgress({ status: step.progress });
        push({ kind: "progress", summary: `Progress: ${step.progress}`, tool: { name: "mcp__work__report_progress", input: { status: step.progress } } });
      } else if ("submit" in step) {
        const result = await workPort.submitOutputs(step.submit);
        if (result.accepted) submitted = true;
        push({
          kind: "submit",
          summary: result.accepted ? "Submitted outputs" : `Submit rejected: ${result.instruction}`,
          detail: result.instruction,
          tool: { name: "mcp__work__submit_outputs", input: step.submit },
        });
      } else if ("deny" in step) {
        denials++;
        push({ kind: "denial", summary: step.deny.reason, detail: step.deny.reason, tool: { name: step.deny.tool, input: {}, isError: true } });
      } else if ("end" in step) {
        forcedOutcome = step.end;
        break;
      }
    }
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    push({ kind: "error", summary: truncate(message, 300), detail: message });
    forcedOutcome = "error";
  }

  let outcome: RunOutcome = forcedOutcome ?? (submitted ? "submitted" : openBlockingQuestion ? "blocked" : "no_submit");
  if (variant === "no-submit" && forcedOutcome === null) outcome = "no_submit";

  push({ kind: "result", summary: `Run ended: ${outcome} — ${stepCount} turn${stepCount === 1 ? "" : "s"}, $0.0000`, costUsd: 0 });

  return {
    outcome,
    sessionId: `fake-${req.runId}`,
    costUsd: 0,
    turns: stepCount,
    model: "fake",
    promptHash: null,
    nudged: false,
    denials,
    lastMessage: lastText,
    error: forcedOutcome === "error" ? "fake script error" : null,
  };
}
